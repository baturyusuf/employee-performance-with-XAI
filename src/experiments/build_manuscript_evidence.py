def _execute_stage(context: StageContext, stage: str, *, reuse_compatible: bool) -> list[Path]:
    if stage not in STAGE_RUNNERS:
        raise ManuscriptBuildError(f"Unknown manuscript stage: {stage}")
    if reuse_compatible and _stage_cache_valid(context, stage):
        metadata_path = _stage_metadata_path(context, stage)
        metadata = json.loads(metadata_path.read_text(encoding="utf-8"))
        return [
            *(PROJECT_ROOT / record["path"] for record in metadata["outputs"]),
            metadata_path,
        ]
    stage_dir = context.run_dir / stage
    if stage_dir.exists() and any(stage_dir.iterdir()):
        raise ManuscriptBuildError(
            f"Stage directory is non-empty but lacks a compatible cache contract: {stage_dir}. "
            "Use a new run ID or preserve/archive the incompatible directory."
        )
    stage_dir.mkdir(parents=True, exist_ok=True)
    started_at = utc_now_iso()
    started = time.perf_counter()
    result = STAGE_RUNNERS[stage](context)
    outputs = _paths_from_result(result, stage_dir)
    metadata = _write_stage_metadata(
        context,
        stage,
        outputs,
        started_at=started_at,
        elapsed_seconds=time.perf_counter() - started,
    )
    return [*outputs, metadata]


def _artifact_type(path: Path) -> str:
    suffix = path.suffix.lower().lstrip(".")
    if suffix in {"png", "svg", "pdf"}:
        return "figure"
    if suffix in {"csv", "json", "jsonl", "parquet"}:
        return "machine_readable_evidence"
    if suffix in {"md", "txt"}:
        return "report"
    return suffix or "file"


def _register_stage_files(
    context: StageContext,
    stage: str,
    files: Sequence[Path],
) -> None:
    already = {
        record.get("path")
        for record in context.manifest.get("output_files", [])
        if isinstance(record, Mapping)
    }
    for path in sorted(set(file.resolve() for file in files), key=lambda item: str(item)):
        portable = _portable(path)
        if portable in already:
            continue
        register_artifact(
            context.manifest,
            path,
            project_root=PROJECT_ROOT,
            stage=stage,
            artifact_type=_artifact_type(path),
            artifact_run_id=context.run_id,
            artifact_config_hash=context.config_hash,
        )
        already.add(portable)


def build_final_evidence_manifest(
    run_dir: str | Path,
    *,
    run_id: str,
    config_hash: str,
    exclude_names: Iterable[str] = ("run_manifest.json", "final_evidence_manifest.csv", "final_evidence_manifest.json"),
) -> Dict[str, Path]:
    """Create independent CSV/JSON hashes for every final package artifact."""

    root = Path(run_dir).resolve()
    rows: list[dict[str, Any]] = []
    excluded = set(exclude_names)
    for path in _all_files(root, exclude_names=excluded):
        relative = path.relative_to(root).as_posix()
        stage = relative.split("/", 1)[0]
        rows.append(
            {
                "run_id": run_id,
                "config_hash": config_hash,
                "stage": stage,
                "path": relative,
                "file_type": _artifact_type(path),
                "size_bytes": path.stat().st_size,
                "sha256": sha256_file(path),
            }
        )
    if not rows:
        raise ManuscriptBuildError("Cannot build an empty final evidence manifest.")
    csv_path = root / "final_evidence_manifest.csv"
    with csv_path.open("w", encoding="utf-8", newline="") as stream:
        writer = csv.DictWriter(stream, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)
    json_path = _write_json(
        root / "final_evidence_manifest.json",
        {
            "run_id": run_id,
            "config_hash": config_hash,
            "hash_algorithm": "sha256",
            "n_files": len(rows),
            "files": rows,
        },
    )
    return {"csv": csv_path, "json": json_path}


def validate_final_evidence_manifest(
    manifest_path: str | Path,
    *,
    run_dir: str | Path,
    expected_run_id: str,
    expected_config_hash: str,
) -> dict[str, Any]:
    path = Path(manifest_path)
    root = Path(run_dir).resolve()
    payload = json.loads(path.read_text(encoding="utf-8"))
    errors: list[str] = []
    if payload.get("run_id") != expected_run_id:
        errors.append("run_id mismatch")
    if payload.get("config_hash") != expected_config_hash:
        errors.append("config_hash mismatch")
    records = payload.get("files")
    if not isinstance(records, list) or not records:
        errors.append("files must be a non-empty list")
        records = []
    seen: set[str] = set()
    for record in records:
        relative = record.get("path") if isinstance(record, Mapping) else None
        if not isinstance(relative, str) or not relative:
            errors.append("manifest record has no path")
            continue
        if relative in seen:
            errors.append(f"duplicate path: {relative}")
        seen.add(relative)
        target = (root / relative).resolve()
        try:
            target.relative_to(root)
        except ValueError:
            errors.append(f"path escapes run root: {relative}")
            continue
        if not target.is_file():
            errors.append(f"missing file: {relative}")
            continue
        if sha256_file(target) != record.get("sha256"):
            errors.append(f"hash mismatch: {relative}")
        if target.stat().st_size != record.get("size_bytes"):
            errors.append(f"size mismatch: {relative}")
        if record.get("run_id") != expected_run_id or record.get("config_hash") != expected_config_hash:
            errors.append(f"identity mismatch: {relative}")
    if errors:
        raise ManuscriptBuildError("Invalid final evidence manifest:\n- " + "\n- ".join(errors))
    return {"status": "passed", "n_files": len(records)}


def _validate_primary_artifacts(context: StageContext) -> None:
    targets = [
        context.run_dir / "shap" / "global_grouped_shap_importance.csv",
        context.run_dir / "shap" / "local_grouped_shap_values.csv",
        context.run_dir / "shap" / "fold_feature_rankings.csv",
    ]
    local_dir = context.run_dir / "shap" / "local_reason_codes"
    if local_dir.is_dir():
        targets.extend(path for path in local_dir.rglob("*") if path.is_file())
    for path in targets:
        if not path.is_file():
            raise ManuscriptBuildError(f"Required primary artifact is missing: {path}")
        suffix = path.suffix.lower()
        if suffix in {".csv", ".json", ".jsonl"}:
            validate_artifact_forbidden_features(path, context.config)
        elif suffix in {".md", ".txt"}:
            validate_artifact_forbidden_features(path, context.config, scan_text=True)


