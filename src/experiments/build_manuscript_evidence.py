class ManuscriptBuildError(RuntimeError):
    """Raised when a canonical stage or final package fails its contract."""


class BaselineReferenceDecisionRequired(ManuscriptBuildError):
    """Raised when a baseline has a conclusive paired-OOF advantage over XGBoost."""


def validate_scope_release_ready(scopes: Mapping[str, Any], scope_name: str) -> Mapping[str, Any]:
    """Reject an unknown or technically incomplete canonical evidence scope."""

    if scope_name not in CANONICAL_STAGE_ORDERS:
        raise ManuscriptBuildError(f"Unknown canonical evidence scope: {scope_name!r}.")
    definition = scopes.get(scope_name)
    if not isinstance(definition, Mapping):
        raise ManuscriptBuildError(f"Evidence scope {scope_name!r} is not declared by the config.")
    configured_stages = tuple(str(value) for value in definition.get("stages", ()))
    if configured_stages != CANONICAL_STAGE_ORDERS[scope_name]:
        raise ManuscriptBuildError(
            f"Evidence scope {scope_name!r} stage contract differs from the canonical registry."
        )
    if definition.get("release_ready") is not True:
        reason = str(definition.get("blocking_reason", "technical freeze is incomplete"))
        raise ManuscriptBuildError(
            f"Evidence scope {scope_name!r} is not release-ready: {reason}"
        )
    missing_runners = sorted(set(configured_stages).difference(STAGE_RUNNERS))
    if missing_runners:
        raise ManuscriptBuildError(
            f"Evidence scope {scope_name!r} has no registered runner for stages: {missing_runners}."
        )
    return definition


def validate_scope_artifact_paths(scope_name: str, relative_paths: Iterable[str]) -> None:
    """Fail closed when a package path lies outside its immutable stage allowlist."""

    if scope_name not in CANONICAL_STAGE_ORDERS:
        raise ManuscriptBuildError(f"Unknown artifact evidence scope: {scope_name!r}.")
    allowed_prefixes = tuple(f"{stage}/" for stage in CANONICAL_STAGE_ORDERS[scope_name]) + (
        "run_inputs/",
    )
    errors: list[str] = []
    for raw_path in relative_paths:
        normalized = str(raw_path).replace("\\", "/").lstrip("./")
        path = Path(normalized)
        if not normalized or path.is_absolute() or ".." in path.parts:
            errors.append(f"invalid scope path: {raw_path!r}")
            continue
        if normalized in _SCOPE_ROOT_ARTIFACTS or normalized.startswith(allowed_prefixes):
            continue
        errors.append(f"forbidden or out-of-scope path: {normalized}")
    if errors:
        raise ManuscriptBuildError("Artifact scope validation failed:\n- " + "\n- ".join(errors))


@dataclass(frozen=True)
class StageContext:
    config_path: Path
    config: Mapping[str, Any]
    settings: Mapping[str, Any]
    run_dir: Path
    run_id: str
    config_hash: str
    manifest: MutableMapping[str, Any]
    evidence_scope: str = "core"
    scope_contract: Mapping[str, Any] | None = None


def _validate_loaded_dataset_receipt(
    context: StageContext,
    dataset_key: str,
    observed: Mapping[str, Any],
) -> None:
    """Bind a stage's freshly loaded bytes to the manifest's verified receipt."""

    receipts = context.manifest.get("actual_input_receipts")
    expected = receipts.get(dataset_key) if isinstance(receipts, Mapping) else None
    if not isinstance(expected, Mapping):
        raise ManuscriptBuildError(
            f"Run manifest has no actual-input receipt for {dataset_key!r}."
        )
    identity_fields = (*ACTUAL_INPUT_IDENTITY_FIELDS, "size_bytes")
    differences = {
        field: {"manifest": expected.get(field), "stage_loader": observed.get(field)}
        for field in identity_fields
        if expected.get(field) != observed.get(field)
    }
    if differences:
        raise ManuscriptBuildError(
            f"Stage loader receipt for {dataset_key!r} does not match the run manifest: "
            + json.dumps(differences, sort_keys=True, ensure_ascii=True)
        )


def _validated_side_input_path(
    context: StageContext,
    side_input_key: str,
    configured_path: str | Path,
) -> tuple[Path, str]:
    """Resolve and re-hash a side input against the scoped manifest record."""

    records = context.manifest.get("side_input_hashes")
    record = records.get(side_input_key) if isinstance(records, Mapping) else None
    if not isinstance(record, Mapping):
        raise ManuscriptBuildError(
            f"Run manifest has no scoped side-input record for {side_input_key!r}."
        )
    candidate = Path(configured_path)
    if not candidate.is_absolute():
        candidate = PROJECT_ROOT / candidate
    candidate = candidate.resolve()
    expected = (PROJECT_ROOT / str(record.get("path", ""))).resolve()
    if candidate != expected:
        raise ManuscriptBuildError(
            f"Configured {side_input_key!r} path does not match the run manifest: "
            f"configured={_portable(candidate)!r}, manifest={record.get('path')!r}."
        )
    if not candidate.is_file():
        raise ManuscriptBuildError(f"Scientific side input is missing: {_portable(candidate)}")
    digest = sha256_file(candidate)
    if digest != record.get("sha256") or candidate.stat().st_size != record.get("size_bytes"):
        raise ManuscriptBuildError(
            f"Scientific side input {side_input_key!r} changed after manifest creation."
        )
    return candidate, digest


def _write_json(path: Path, payload: Mapping[str, Any]) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    serialized = json.dumps(payload, indent=2, sort_keys=True, ensure_ascii=False) + "\n"
    descriptor, temporary = tempfile.mkstemp(
        prefix=f".{path.name}.", suffix=".tmp", dir=path.parent, text=True
    )
    try:
        with os.fdopen(descriptor, "w", encoding="utf-8", newline="\n") as stream:
            stream.write(serialized)
        os.replace(temporary, path)
    except Exception:
        try:
            os.unlink(temporary)
        except OSError:
            pass
        raise
    return path


def _portable(path: Path) -> str:
    resolved = path.resolve()
    try:
        return resolved.relative_to(PROJECT_ROOT.resolve()).as_posix()
    except ValueError:
        return str(resolved)


def _all_files(directory: Path, *, exclude_names: Iterable[str] = ()) -> list[Path]:
    excluded = set(exclude_names)
    return sorted(
        (
            path
            for path in directory.rglob("*")
            if path.is_file()
            and path.name not in excluded
            and "__pycache__" not in path.parts
            and not path.name.startswith(".")
        ),
        key=lambda path: path.relative_to(directory).as_posix(),
    )


def _stage_metadata_path(context: StageContext, stage: str) -> Path:
    return context.run_dir / stage / "stage_contract.json"


def _stage_cache_valid(context: StageContext, stage: str) -> bool:
    path = _stage_metadata_path(context, stage)
    if not path.is_file():
        return False
    try:
        payload = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return False
    if payload.get("status") != "complete":
        return False
    if payload.get("run_id") != context.run_id or payload.get("config_hash") != context.config_hash:
        return False
    if payload.get("evidence_scope") != context.manifest.get("evidence_scope"):
        return False
    if payload.get("scope_contract_hash") != context.manifest.get("scope_contract_hash"):
        return False
    if payload.get("git_commit") != context.manifest.get("git_commit"):
        return False
    if payload.get("source_tree_hash") != context.manifest.get("source_tree_hash"):
        return False
    if payload.get("dataset_hashes") != context.manifest.get("dataset_hashes"):
        return False
    if payload.get("actual_input_receipts") != context.manifest.get("actual_input_receipts"):
        return False
    if payload.get("side_input_hashes") != context.manifest.get("side_input_hashes"):
        return False
    if payload.get("scientific_input_hash") != context.manifest.get("scientific_input_hash"):
        return False
    outputs = payload.get("outputs")
    if not isinstance(outputs, list) or not outputs:
        return False
    for record in outputs:
        if not isinstance(record, Mapping):
            return False
        raw_path = record.get("path")
        digest = record.get("sha256")
        if not isinstance(raw_path, str) or not isinstance(digest, str):
            return False
        output = PROJECT_ROOT / raw_path
        if not output.is_file() or sha256_file(output) != digest:
            return False
    return True


def _write_stage_metadata(
    context: StageContext,
    stage: str,
    outputs: Sequence[Path],
    *,
    started_at: str,
    elapsed_seconds: float,
) -> Path:
    metadata_path = _stage_metadata_path(context, stage)
    output_rows = [
        {
            "path": _portable(path),
            "sha256": sha256_file(path),
            "size_bytes": path.stat().st_size,
        }
        for path in outputs
        if path.is_file() and path.resolve() != metadata_path.resolve()
    ]
    if not output_rows:
        raise ManuscriptBuildError(f"Stage {stage!r} produced no files.")
    return _write_json(
        metadata_path,
        {
            "stage": stage,
            "status": "complete",
            "run_id": context.run_id,
            "config_hash": context.config_hash,
            "evidence_scope": context.manifest.get("evidence_scope"),
            "scope_contract_hash": context.manifest.get("scope_contract_hash"),
            "git_commit": context.manifest.get("git_commit"),
            "source_tree_hash": context.manifest.get("source_tree_hash"),
            "dataset_hashes": context.manifest.get("dataset_hashes"),
            "actual_input_receipts": context.manifest.get("actual_input_receipts"),
            "side_input_hashes": context.manifest.get("side_input_hashes"),
            "scientific_input_hash": context.manifest.get("scientific_input_hash"),
            "started_at": started_at,
            "ended_at": utc_now_iso(),
            "elapsed_seconds": elapsed_seconds,
            "outputs": output_rows,
        },
    )


def _paths_from_result(result: Mapping[str, Any], stage_dir: Path) -> list[Path]:
    paths: set[Path] = set()
    for value in result.values():
        if isinstance(value, (str, Path)):
            candidate = Path(value)
            if candidate.is_file():
                paths.add(candidate.resolve())
        elif isinstance(value, Sequence) and not isinstance(value, (str, bytes)):
            for item in value:
                if isinstance(item, (str, Path)) and Path(item).is_file():
                    paths.add(Path(item).resolve())
    paths.update(path.resolve() for path in _all_files(stage_dir, exclude_names={"stage_contract.json"}))
    return sorted(paths, key=lambda path: str(path))


def _run_shared_folds(context: StageContext) -> Mapping[str, Any]:
    from src.data.canonical_loader import load_canonical_dataset
    from src.experiments.shared_folds import generate_shared_folds, write_shared_folds

    loaded = load_canonical_dataset(context.config_path, "inx_primary")
    _validate_loaded_dataset_receipt(context, "inx_primary", loaded.receipt)
    target_column = str(context.settings["target"]["column"])
    identifiers = context.settings["governance_fields"]["identifier_fields"]
    if not isinstance(identifiers, list) or len(identifiers) != 1:
        raise ManuscriptBuildError("The shared-fold contract requires exactly one canonical identifier.")
    cv = context.settings["evaluation"]["cv"]
    nested = context.settings["model"]["nested_tuning"]
    seeds = context.settings["seeds"]
    outer_seed = int(seeds[str(cv["seed"])])
    inner_seed = int(seeds[str(nested["inner_seed"])])
    receipt = context.manifest["actual_input_receipts"]["inx_primary"]
    artifacts = generate_shared_folds(
        loaded.frame,
        target_column=target_column,
        id_column=str(identifiers[0]),
        run_id=context.run_id,
        config_hash=context.config_hash,
        scientific_input_hash=str(context.manifest["scientific_input_hash"]),
        dataset_key="inx_primary",
        dataset_sha256=str(receipt["actual_sha256"]),
        outer_splits=int(cv["n_splits"]),
        inner_splits=int(nested["inner_splits"]),
        seed=outer_seed,
        inner_seed=inner_seed,
    )
    return write_shared_folds(artifacts, context.run_dir / "shared_folds")


