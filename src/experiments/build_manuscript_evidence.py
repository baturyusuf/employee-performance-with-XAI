def _write_json(path: Path, payload: Mapping[str, Any]) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    serialized = json.dumps(payload, indent=2, sort_keys=True, ensure_ascii=False) + "\n"
    descriptor, temporary = tempfile.mkstemp(
        prefix=f".{path.name}.", suffix=".tmp", dir=path.parent, text=True
    )
    try:
        with os.fdopen(descriptor, "w", encoding="utf-8", newline="\n") as stream:
            stream.write(serialized)
        os.replace(temporary, path)
    except Exception:
        try:
            os.unlink(temporary)
        except OSError:
            pass
        raise
    return path


def _portable(path: Path) -> str:
    resolved = path.resolve()
    try:
        return resolved.relative_to(PROJECT_ROOT.resolve()).as_posix()
    except ValueError:
        return str(resolved)


def _all_files(directory: Path, *, exclude_names: Iterable[str] = ()) -> list[Path]:
    excluded = set(exclude_names)
    return sorted(
        (
            path
            for path in directory.rglob("*")
            if path.is_file()
            and path.name not in excluded
            and "__pycache__" not in path.parts
            and not path.name.startswith(".")
        ),
        key=lambda path: path.relative_to(directory).as_posix(),
    )


def _stage_metadata_path(context: StageContext, stage: str) -> Path:
    return context.run_dir / stage / "stage_contract.json"


def _stage_cache_valid(context: StageContext, stage: str) -> bool:
    path = _stage_metadata_path(context, stage)
    if not path.is_file():
        return False
    try:
        payload = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return False
    if payload.get("status") != "complete":
        return False
    if payload.get("run_id") != context.run_id or payload.get("config_hash") != context.config_hash:
        return False
    if payload.get("source_tree_hash") != context.manifest.get("source_tree_hash"):
        return False
    if payload.get("dataset_hashes") != context.manifest.get("dataset_hashes"):
        return False
    outputs = payload.get("outputs")
    if not isinstance(outputs, list) or not outputs:
        return False
    for record in outputs:
        if not isinstance(record, Mapping):
            return False
        raw_path = record.get("path")
        digest = record.get("sha256")
        if not isinstance(raw_path, str) or not isinstance(digest, str):
            return False
        output = PROJECT_ROOT / raw_path
        if not output.is_file() or sha256_file(output) != digest:
            return False
    return True


def _write_stage_metadata(
    context: StageContext,
    stage: str,
    outputs: Sequence[Path],
    *,
    started_at: str,
    elapsed_seconds: float,
) -> Path:
    metadata_path = _stage_metadata_path(context, stage)
    output_rows = [
        {
            "path": _portable(path),
            "sha256": sha256_file(path),
            "size_bytes": path.stat().st_size,
        }
        for path in outputs
        if path.is_file() and path.resolve() != metadata_path.resolve()
    ]
    if not output_rows:
        raise ManuscriptBuildError(f"Stage {stage!r} produced no files.")
    return _write_json(
        metadata_path,
        {
            "stage": stage,
            "status": "complete",
            "run_id": context.run_id,
            "config_hash": context.config_hash,
            "git_commit": context.manifest.get("git_commit"),
            "source_tree_hash": context.manifest.get("source_tree_hash"),
            "dataset_hashes": context.manifest.get("dataset_hashes"),
            "started_at": started_at,
            "ended_at": utc_now_iso(),
            "elapsed_seconds": elapsed_seconds,
            "outputs": output_rows,
        },
    )


def _paths_from_result(result: Mapping[str, Any], stage_dir: Path) -> list[Path]:
    paths: set[Path] = set()
    for value in result.values():
        if isinstance(value, (str, Path)):
            candidate = Path(value)
            if candidate.is_file():
                paths.add(candidate.resolve())
        elif isinstance(value, Sequence) and not isinstance(value, (str, bytes)):
            for item in value:
                if isinstance(item, (str, Path)) and Path(item).is_file():
                    paths.add(Path(item).resolve())
    paths.update(path.resolve() for path in _all_files(stage_dir, exclude_names={"stage_contract.json"}))
    return sorted(paths, key=lambda path: str(path))


